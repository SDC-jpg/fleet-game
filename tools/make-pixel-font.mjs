const w = CELL_W * FONT_CHARS.length;
const data = new Uint8Array(w * CELL_H * 4);
[...FONT_CHARS].forEach((ch, i) => {
  const rows = G[ch];
  if (!rows) throw new Error(`no glyph for ${JSON.stringify(ch)}`);
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c !== '#') return;
      data.set([255, 255, 255, 255], ((y + 1) * w + i * CELL_W + x) * 4);
    }),
  );
});

// ---------- Tiny PNG writer ----------
const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
function chunk(type, body) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(body.length);
  const all = Buffer.concat([Buffer.from(type, 'ascii'), body]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(all));
  return Buffer.concat([len, all, crc]);
}
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(w, 0);
ihdr.writeUInt32BE(CELL_H, 4);
ihdr[8] = 8;
ihdr[9] = 6;
const raw = Buffer.alloc((w * 4 + 1) * CELL_H);
for (let y = 0; y < CELL_H; y++) Buffer.from(data.buffer, y * w * 4, w * 4).copy(raw, y * (w * 4 + 1) + 1);
const png = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
writeFileSync(PATH, png);
